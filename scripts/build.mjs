// Build step: bundles the country data and downloads the map topology.
// Run with: node scripts/build.mjs   (Node 18 or newer, no dependencies)
import { readdir, readFile, writeFile, mkdir, access } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "site", "data");
const MAP_URL = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json";

await mkdir(out, { recursive: true });

// 1. Country data -> site/data/countries.json
const dir = join(root, "data", "countries");
const files = (await readdir(dir)).filter((f) => f.endsWith(".json")).sort();
const countries = [];
for (const f of files) {
  const c = JSON.parse(await readFile(join(dir, f), "utf8"));
  for (const key of ["id", "name", "capital", "flag", "lonLat", "modes"]) {
    if (!c[key]) throw new Error(`${f}: missing "${key}"`);
  }
  for (const m of ["train", "tram", "bus", "airport"]) {
    if (!c.modes[m]) throw new Error(`${f}: missing mode "${m}"`);
  }
  countries.push(c);
}
const generalTips = JSON.parse(await readFile(join(root, "data", "general-tips.json"), "utf8"));

// Route hub guides -> site/data/routes.json (optional folder)
const routesDir = process.env.ROUTES_DIR || join(root, "data", "routes");
const routes = [];
for (const f of (await readdir(routesDir).catch(() => [])).filter((n) => n.endsWith(".json")).sort()) {
  const r = JSON.parse(await readFile(join(routesDir, f), "utf8"));
  for (const key of ["id", "title", "from", "to", "stats", "sections"]) {
    if (!r[key]) throw new Error(`routes/${f}: missing "${key}"`);
  }
  routes.push(r);
}
console.log(`routes: ${routes.length}`);
await writeFile(join(out, "countries.json"), JSON.stringify({ generalTips, countries, routes }));
console.log(`countries.json: ${countries.length} countries`);

// 2. Affiliate config -> site/data/affiliates.json
const aff = JSON.parse(await readFile(join(root, "data", "affiliates.json"), "utf8"));
delete aff._howTo;
await writeFile(join(out, "affiliates.json"), JSON.stringify(aff));

// 2b. Same data as a script, so the site also works when index.html is opened straight from disk
await writeFile(join(out, "data.js"), "window.ETG_DATA=" + JSON.stringify({ generalTips, countries, routes, affiliates: aff }) + ";\n");
await writeFile(join(out, "routes.json"), JSON.stringify(routes));

// 3. City list for the news function
const cities = Object.fromEntries(countries.map((c) => [c.id, { city: c.capital, country: c.name }]));
await writeFile(
  join(root, "netlify", "functions", "news", "cities.mjs"),
  "// Generated by scripts/build.mjs - do not edit\nexport default " + JSON.stringify(cities, null, 2) + ";\n"
);

// 3b. Static pages with their own URL, title and description (good for search engines):
//     /<capital>/ for each city and /routes/<id>/ for each route guide, plus sitemap.xml and robots.txt.
const siteUrl = (process.env.SITE_URL || process.env.URL || "https://example.com").replace(/\/$/, "");
const siteDir = join(root, "site");
const h = (t) => String(t ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
function seo({ title, desc, path }) {
  const url = siteUrl + path;
  return `<!--seo:start-->
<link rel="canonical" href="${url}">
<meta property="og:site_name" content="Euro Transit Guide">
<meta property="og:title" content="${h(title)}">
<meta property="og:description" content="${h(desc)}">
<meta property="og:type" content="website">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${siteUrl}/og-image.png">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<!--seo:end-->`;
}
const SEO_RE = /<!--seo:start-->[\s\S]*?<!--seo:end-->/;
// the home page gets its tags written into site/index.html itself
const homeTitle = "Euro Transit Guide: public transport in every European capital";
const homeDesc = "Public transport guides for European capitals: trains, trams, metro, buses and airport links, with ticket prices, tips, apps and live transport news.";
let homeHtml = await readFile(join(siteDir, "index.html"), "utf8");
homeHtml = homeHtml.replace(SEO_RE, seo({ title: homeTitle, desc: homeDesc, path: "/" }));
await writeFile(join(siteDir, "index.html"), homeHtml);
const template = homeHtml;
const slug = (t) => t.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const urls = [siteUrl + "/"];
const seen = new Set();
async function page(path, { title, desc, hash, body, ld }) {
  if (seen.has(path)) throw new Error(`duplicate page path ${path}`);
  seen.add(path);
  let html = template
    .replace(/<title>.*?<\/title>/, `<title>${h(title)}</title>`)
    .replace(/(<meta name="description" content=")[^"]*(">)/, `$1${h(desc)}$2`)
    .replace('href="css/', 'href="/css/').replace('src="data/data.js"', 'src="/data/data.js"').replace('src="js/app.js"', 'src="/js/app.js"')
    .replace(SEO_RE, seo({ title, desc, path }))
    .replace("</head>", (ld ? `<script type="application/ld+json" id="ld">${JSON.stringify(ld).replace(/</g, "\\u003c")}</script>\n` : "") +
      `<script>if(!location.hash)history.replaceState(null,"","#${hash}");</script>\n</head>`)
    .replace("<main>", `<main>\n<noscript>${body}</noscript>`);
  const dest = join(siteDir, path.replace(/^\//, ""));
  await mkdir(dest, { recursive: true });
  await writeFile(join(dest, "index.html"), html);
  urls.push(siteUrl + path);
}
for (const c of countries) {
  const body = `<h1>${h(c.capital)} public transport guide</h1><p>${h(c.modes.train.sum)}</p><p>${h(c.modes.tram.sum)}</p><p>${h(c.modes.airport.sum)}</p>`;
  await page(`/${slug(c.capital)}/`, {
    title: `${c.capital} public transport guide for visitors · Euro Transit Guide`,
    desc: `${c.capital} public transport for visitors: train, tram and metro, bus and airport links, ticket prices, tips, apps and news.`,
    hash: c.id.toLowerCase(), body,
  });
}
for (const r of routes) {
  const ld = (r.faq || []).length ? { "@context": "https://schema.org", "@type": "FAQPage", mainEntity: r.faq.map((x) => ({ "@type": "Question", name: x.q, acceptedAnswer: { "@type": "Answer", text: x.a } })) } : null;
  const body = `<h1>${h(r.title)}</h1><p>${h(r.summary || "")}</p><ul>${r.stats.map((x) => `<li>${h(x.label)}: ${h(x.value)}</li>`).join("")}</ul>`;
  await page(`/routes/${r.id}/`, { title: `${r.title} · Euro Transit Guide`, desc: r.summary || r.short || r.title, hash: "route-" + r.id, body, ld });
}
// 3c. Plain legal pages (no app script): /privacy/ and /affiliate-disclosure/
const contact = process.env.CONTACT_EMAIL || "";
if (!contact) console.warn("CONTACT_EMAIL is not set: the legal pages will have no contact line.");
const UPDATED = "11 November 2026";
const contactLine = contact ? `<p>Questions about this page or your data: <a href="mailto:${h(contact)}">${h(contact)}</a>.</p>` : "";
